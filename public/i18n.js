  const DICT = { fi, en };
  const LANGS = ["fi", "en"];
  const listeners = [];

  function detect() {
    try {
      const q = new URLSearchParams(location.search).get("lang");
      if (LANGS.includes(q)) return q;
    } catch {}
    try {
      const s = localStorage.getItem("tk_lang");
      if (LANGS.includes(s)) return s;
    } catch {}
    return "fi";
  }
  let lang = detect();

  function has(key) {
    return DICT[lang][key] != null || DICT.en[key] != null;
  }
  function t(key, vars) {
    let s = DICT[lang][key];
    if (s == null) s = DICT.en[key];
    if (s == null) return key;
    if (typeof s === "function") return s(vars || {});
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m)) : s;
  }

  function apply(root) {
    const r = root || document;
    document.documentElement.lang = lang;
    r.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
    r.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
    r.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
    r.querySelectorAll("[data-i18n-unit]").forEach((el) => { el.dataset.unit = t(el.dataset.i18nUnit); });
    document.querySelectorAll("[data-lang]").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.lang === lang)));
  }

  function setLang(l) {
    if (!LANGS.includes(l) || l === lang) return;
    lang = l;
    try { localStorage.setItem("tk_lang", l); } catch {}
    try {
      const u = new URL(location.href);
      if (u.searchParams.has("lang")) { u.searchParams.delete("lang"); history.replaceState(null, "", u.pathname + u.search + u.hash); }
    } catch {}
    apply();
    listeners.forEach((fn) => { try { fn(lang); } catch (e) { console.error(e); } });
  }

  document.addEventListener("click", (ev) => {
    const b = ev.target.closest && ev.target.closest("[data-lang]");
    if (b) setLang(b.dataset.lang);
  });

  window.I18N = {
    t, has, apply, setLang,
    get lang() { return lang; },
    locale: () => (lang === "fi" ? "fi-FI" : "en-GB"),
    onChange: (fn) => listeners.push(fn)
  };
  apply();
