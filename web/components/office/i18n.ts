/** "Long side A" → "Pitkä sivu A". */
export function sideText(i: T, name: string) {
  const m = /^(Long side|Short side|Gable end|Wall) (\w+)$/.exec(name || "");
  if (!m) return name;
  const k = m[1] === "Long side" ? "side.long" : m[1] === "Short side" ? "side.short" : m[1] === "Wall" ? "side.wall" : "side.gable";
  return i.t(k, { x: m[2] });
}

/** Price or invoice line in the chosen language, using the numbers stored with it. */
export function lineText(i: T, l: Pick<QuoteLine, "key" | "label"> & { vars?: Record<string, unknown> | null }, q?: { rentDays?: number; trucks?: number }) {
  const v = (l.vars || {}) as Record<string, string | number>;
  const fromLabel = (re: RegExp) => (re.exec(l.label || "") || [])[1] || "";
  const pm = /^(missing|damaged)_(\w+)$/.exec(l.key);
  if (pm) return i.t(pm[1] === "missing" ? "line.missing" : "line.damaged", { part: partLabel(i, String(v.part || pm[2])) });
  switch (l.key) {
    case "rent":
      return i.t("line.rent", { days: v.days ?? q?.rentDays ?? fromLabel(/(\d+) days/) });
    case "transport": {
      const n = Number(v.loads ?? q?.trucks ?? 1);
      return n > 1 ? i.t("line.transportN", { n }) : i.t("line.transport");
    }
    case "premium": {
      const tier = String(v.tier || (/^Emergency/.test(l.label) ? "emergency" : "express"));
      return i.t("line.premium", { tier: i.tk(`tier.${tier}`, undefined, tier), pct: v.pct ?? fromLabel(/\+([\d.]+)%/) });
    }
    case "levels":
      return i.t("line.levels", { m: v.m ?? fromLabel(/(\d+) m/) });
    case "sheeting":
      return i.t("line.sheeting", { m2: v.m2 ?? "" });
    case "roofRent":
      return i.t("line.roofRent", { m2: v.m2 ?? "", days: v.days ?? q?.rentDays ?? "" });
    case "roofWork":
      return i.t("line.roofWork");
    case "discount":
      return i.t("line.discount", { pct: v.pct ?? fromLabel(/−?([\d.]+) %/) });
    default:
      return i.tk(`line.${l.key}`, undefined, l.label);
  }
}

/** Office alerts are stored as English sentences; rebuild them in the chosen language when the pattern is known. */
export function alertText(i: T, a: Alert): string {
  const s = a.text || "";
  const d = (iso: string) => day(iso, i.lang);
  let m: RegExpExecArray | null;
  switch (a.type) {
    case "new_order":
      if ((m = /^New order (\S+): (.*), (\d+(?:\.\d+)?) m², start (\d{4}-\d{2}-\d{2})$/.exec(s))) return i.t("al.new_order", { ref: m[1], address: m[2], area: m[3], date: d(m[4]) });
      break;
    case "change_request":
      if ((m = /^(\S+): customer asks for (.*)$/.exec(s))) {
        const w = m[2];
        let what = w;
        let x: RegExpExecArray | null;
        if ((x = /^rental (\d+) days$/.exec(w))) what = i.t("al.what.days", { n: x[1] });
        else if ((x = /^pickup on (\d{4}-\d{2}-\d{2})$/.exec(w))) what = i.t("al.what.pickup", { date: d(x[1]) });
        else if (w === "scaffold size changes") what = i.t("al.what.house");
        else if (w === "other change") what = i.t("al.what.other");
        return i.t("al.change_request", { ref: m[1], what });
      }
      break;
    case "problem":
      if ((m = /^(\S+): (.+?) reports (.*)$/.exec(s))) {
        let what = m[3];
        const x = /^size differs \(new price (.*) €\)$/.exec(what);
        if (x) what = i.t("al.what.size", { price: Number.isFinite(Number(x[1])) ? money(Number(x[1]), i.lang) : `${x[1]} €` });
        else if (what === "problem on site") what = i.t("al.what.problem");
        return i.t("al.problem", { ref: m[1], name: m[2], what });
      }
      break;
    case "weather":
      if ((m = /^(\S+): wind gusts up to (\d+) m\/s forecast – (.*)$/.exec(s))) return i.t("al.weather", { ref: m[1], n: m[2], address: m[3] });
      break;
    case "stock_short":
      if ((m = /^(\S+): (\d+) parts missing or damaged at pickup$/.exec(s))) return i.t("al.stock_short", { ref: m[1], n: m[2] });
      break;
    case "customer_message":
      if ((m = /^(\S+): message from (.*)$/.exec(s))) return i.t("al.customer_message", { ref: m[1], name: m[2] });
      break;
    case "contact":
      if ((m = /^Contact message from (.*)$/.exec(s))) return i.t("al.contact", { name: m[1] });
      break;
    case "review":
      if ((m = /^(\S+): (\d)\/5 stars from (.*)$/.exec(s))) return i.t("al.review", { ref: m[1], n: m[2], name: m[3] });
      break;
    case "pickup_requested":
      if ((m = /^(\S+): pickup requested – (.*)$/.exec(s))) return i.t("al.pickup_requested", { ref: m[1], address: m[2] });
      break;
    case "visit_due":
      if ((m = /^(\S+): inspection visit due – (.*)$/.exec(s))) return i.t("al.visit_due", { ref: m[1], address: m[2] });
      break;
    case "price_change_accepted":
      if ((m = /^(\S+): customer accepted the new price ([\d.]+) €$/.exec(s))) return i.t("al.price_change_accepted", { ref: m[1], total: money(Number(m[2]), i.lang) });
      break;
    case "price_change_declined":
      if ((m = /^(\S+): customer declined the new price ([\d.]+) € \(keeps ([\d.]+) €\)$/.exec(s))) return i.t("al.price_change_declined", { ref: m[1], total: money(Number(m[2]), i.lang), old: money(Number(m[3]), i.lang) });
      break;
    case "price_change_outdated":
      if ((m = /^(\S+): price change outdated/.exec(s))) return i.t("al.price_change_outdated", { ref: m[1] });
      break;
  }
  return s;
}

/** One line of the order's timeline. */
export function historyText(i: T, h: HistoryEntry): string {
  if (h.status) return i.t("hist.status", { status: statusLabel(i, h.status) });
  switch (h.code) {
    case "scheduled":
    case "change_requested":
    case "change_approved":
    case "change_rejected":
    case "arrived":
    case "layout_changed":
    case "price_change_proposed":
    case "price_change_accepted":
    case "price_change_declined":
    case "price_change_withdrawn":
    case "price_change_replaced":
    case "price_change_outdated":
      return i.t(`hist.${h.code}`);
    case "visit":
      return /problem/i.test(h.event || "") ? i.t("hist.visitIssue") : i.t("hist.visitOk");
    case "extended":
      return i.t("hist.extended", { days: h.days ?? "" });
  }
  return h.event || "–";
}

/** One line of the activity log. */
export function auditText(i: T, a: AuditEntry): string {
  const d = (a.detail || {}) as Record<string, unknown>;
  if (a.action === "status") return i.t("audit.status", { from: statusLabel(i, String(d.from || "")), to: statusLabel(i, String(d.to || "")) });
  if (a.action === "scheduled") {
    const parts: string[] = [];
    if (d.date) parts.push(i.t("audit.delivery", { date: `${day(String(d.date), i.lang)}${d.time ? ` ${d.time}` : ""}` }));
    if (d.pickupDate) parts.push(i.t("audit.pickupW", { date: `${day(String(d.pickupDate), i.lang)}${d.pickupTime ? ` ${d.pickupTime}` : ""}` }));
    return i.t("audit.scheduled", { what: parts.join(", ") });
  }
  if (a.action.startsWith("invoice_")) return i.tk(`audit.${a.action}`, { no: String(d.no || "") }, a.action);
  return i.tk(`audit.${a.action}`, undefined, a.action);
}

/** Error message in the chosen language, from the API's error code. */
export function errMessage(i: T, e: unknown): string {
  const err = e as { code?: string; status?: number; message?: string };
  const code = err?.code || "";
  if (code && hasKey(`err.${code}`)) return i.tk(`err.${code}`);
  if (err?.status === 403) return i.t("err.forbidden");
  if (err?.status && err.status >= 500) return i.t("err.server_error");
  return err?.message || i.t("err.server_error");
}
