const DICTS: Record<Lang, Dict> = { fi, en, ru };

export type T = (key: Key, vars?: Vars) => string;
export function makeT(lang: Lang): T {
  const d = DICTS[lang] || fi;
  return (key, vars = {}) => {
    const e = d[key] ?? fi[key];
    if (e === undefined) return key;
    return typeof e === "function" ? e(vars) : e;
  };
}

export const isLang = (v: unknown): v is Lang => v === "fi" || v === "en" || v === "ru";

/* ---------------- Names from the API ---------------- */
export const statusLabel = (t: T, s: OrderStatus) => t(`status.${s}` as Key);
export const jobTypeLabel = (t: T, j: JobType) => t(`jobType.${j}` as Key);
export const roofLabel = (t: T, r: RoofType) => t(`roof.${r}` as Key);
