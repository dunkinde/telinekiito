  ({ loaded: t("load.cta"), on_the_way: t("drive.onTheWay"), arrived: t("drive.arrived"), erected: t("insp.ctaShort"), visit: t("op.visit"), dismantled: t("dis.cta") })[a];

/** Side names come from the engine in English ("Long side A"); show them in the user's language. */
export function sideLabel(t: T, name: string): string {
  const m = /^(Long side|Short side|Gable end) ([A-Z0-9]+)$/.exec(name);
  if (!m) return name;
  return t(m[1] === "Long side" ? "side.long" : m[1] === "Short side" ? "side.short" : "side.gable", { x: m[2] });
}

/** A server error in plain words. `inspection_incomplete` lists the missing checklist points. */
export function errorText(t: T, e: unknown): string {
  const err = e as Partial<ApiError> | null;
  const code = (err && typeof err.code === "string" && err.code) || "";
  if (!code) return t("err.unknown", { code: (err && (err as Error).message) || "?" });
  if (code === "inspection_incomplete") {
    const missing = (err?.info?.missing as InspectionItem[] | undefined) || [];
    return missing.length ? `${t("insp.missing")} ${missing.map((k) => inspLabel(t, k)).join(", ")}` : t("err.inspection_incomplete");
  }
  const key = `err.${code}` as Key;
  if (key in fi) return t(key);
  if (/^http_5/.test(code)) return t("err.server_error");
  return err?.message ? `${err.message}` : t("err.unknown", { code });
}

/* ---------------- Dates, times, numbers ---------------- */
const LOCALE: Record<Lang, string> = { fi: "fi-FI", en: "en-GB", ru: "ru-RU" };
export const locale = (lang: Lang) => LOCALE[lang];

/** "2026-10-08" → "to 8.10." / "Thu 8 Oct" / "чт, 8 окт." */
export function fmtDay(iso: string | null | undefined, lang: Lang, opts: { weekday?: boolean } = {}): string {
  if (!iso) return "—";
  const [y, m, d] = iso.slice(0, 10).split("-").map(Number);
  const date = new Date(y, m - 1, d, 12);
  const weekday = opts.weekday === false ? undefined : ("short" as const);
  if (lang === "fi") return date.toLocaleDateString("fi-FI", { weekday, day: "numeric", month: "numeric" });
  return date.toLocaleDateString(LOCALE[lang], { weekday, day: "numeric", month: "short" });
}
export function fmtWeekday(iso: string, lang: Lang): string {
  const [y, m, d] = iso.slice(0, 10).split("-").map(Number);
  return new Date(y, m - 1, d, 12).toLocaleDateString(LOCALE[lang], { weekday: "short" }).replace(".", "");
}
export function fmtDayNum(iso: string, lang: Lang): string {
  const [, m, d] = iso.slice(0, 10).split("-").map(Number);
  return lang === "en" ? String(d) : `${d}.${m}.`;
}
/** Clock time in Helsinki from a timestamp. */
export function fmtTime(ts: string | null | undefined, lang: Lang): string {
  if (!ts) return "—";
  return new Date(ts).toLocaleTimeString(LOCALE[lang], { hour: "2-digit", minute: "2-digit", timeZone: "Europe/Helsinki" });
}
export function fmtStamp(ts: string | null | undefined, lang: Lang): string {
  if (!ts) return "—";
  const d = new Date(ts);
  const day = d.toLocaleDateString(LOCALE[lang], { day: "numeric", month: lang === "fi" ? "numeric" : "short", timeZone: "Europe/Helsinki" });
  return `${day} ${fmtTime(ts, lang)}`;
}
export function fmtDuration(minutes: number, lang: Lang): string {
  const m = Math.max(0, Math.round(minutes));
  const h = Math.floor(m / 60), r = m % 60;
  const H = lang === "ru" ? "ч" : "h", M = lang === "ru" ? "мин" : "min";
  return h ? `${h} ${H} ${r} ${M}` : `${r} ${M}`;
}
export function fmtNum(n: number, lang: Lang, digits = 1): string {
  return new Intl.NumberFormat(LOCALE[lang], { maximumFractionDigits: digits }).format(n);
}
export function fmtEur(n: number, lang: Lang): string {
  return new Intl.NumberFormat(LOCALE[lang], { style: "currency", currency: "EUR", maximumFractionDigits: 0 }).format(Math.round(n));
}
/** "Today" / "Tomorrow" / "Yesterday" or the date. */
export function relDay(iso: string, today: string, lang: Lang, t: T): string {
  const diff = Math.round((Date.parse(iso.slice(0, 10) + "T00:00:00Z") - Date.parse(today.slice(0, 10) + "T00:00:00Z")) / 864e5);
  if (diff === 0) return t("day.today");
  if (diff === 1) return t("day.tomorrow");
  if (diff === -1) return t("day.yesterday");
  return fmtDay(iso, lang);
}

